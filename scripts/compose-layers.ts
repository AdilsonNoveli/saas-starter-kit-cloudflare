import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "node:url";

// Generates the two composition files the Composition Root consumes:
//
//   1. `packages/app/server/trpc/routers/.composition/layer-routers.ts`,
//      spread into `appRouter`. A layer is picked up when it has BOTH a
//      `layer.manifest.ts` (which names it) and a `server/trpc/router.ts`.
//   2. `packages/app/app/composables/.composition/layer-navigation.ts`, which
//      re-exports every layer manifest so `useLayerNavigation()` can read the
//      sidebar entries declared in them. Only a `layer.manifest.ts` is needed.
//
// This is called automatically from `packages/app/nuxt.config.ts` on every
// `nuxt dev`/`build`/`generate`/`typecheck`/`prepare` invocation — there is no
// manual step to remember. Running `bun scripts/compose-layers.ts` by hand
// still works (useful to inspect the output without booting Nuxt), it just
// calls the same function.
//
// `fileURLToPath(import.meta.url)` rather than Bun's `import.meta.dir`: this
// module is imported both as a standalone Bun script and from inside Nuxt's
// config loader (c12/jiti), and must resolve the same way in both — matches
// the convention already used in `packages/web/nuxt.config.ts`.
const here = fileURLToPath(new URL(".", import.meta.url));

interface DiscoveredLayer {
  /** Directory name under `layers/`, also the npm package suffix. */
  dir: string;
  /** `name` field from the manifest — the key the router is mounted under. */
  name: string;
  /** Whether the layer ships a tRPC router to mount on `appRouter`. */
  hasRouter: boolean;
}

// The manifest is TypeScript importing `@nuxfire/layer-types`, so it can't be
// `import()`ed here without resolving the whole workspace just to read one
// string field. The `name` field is a string literal by contract — read it
// textually, and fall back to the directory name, which the naming
// convention requires to match anyway.
function readManifestName(dir: string, fallback: string): string {
  const text = readFileSync(resolve(dir, "layer.manifest.ts"), "utf8");
  return text.match(/\bname:\s*["'`]([^"'`]+)["'`]/)?.[1] ?? fallback;
}

function discoverLayers(layersDir: string): DiscoveredLayer[] {
  if (!existsSync(layersDir)) return [];

  const found: DiscoveredLayer[] = [];

  for (const entry of readdirSync(layersDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;

    const dir = resolve(layersDir, entry.name);
    // The manifest is what makes a directory a layer at all; a tRPC router is
    // optional (a layer can be frontend-only).
    if (!existsSync(resolve(dir, "layer.manifest.ts"))) continue;

    found.push({
      dir: entry.name,
      name: readManifestName(dir, entry.name),
      hasRouter: existsSync(resolve(dir, "server/trpc/router.ts")),
    });
  }

  return found.sort((a, b) => a.name.localeCompare(b.name));
}

const GENERATED_HEADER = `// GENERATED by scripts/compose-layers.ts — do not edit by hand.
// Regenerated automatically on every Nuxt config load (see
// packages/app/nuxt.config.ts); \`bun scripts/compose-layers.ts\` also works
// standalone if you just want to inspect the output.`;

function write(outFile: string, contents: string) {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, contents);
}

/** A layer directory name turned into a legal JS identifier prefix. */
function importAlias(dir: string) {
  return `${dir.replace(/[^A-Za-z0-9]/g, "_")}Routers`;
}

/**
 * `packages/app/server/trpc/routers/.composition/layer-routers.ts` — the object
 * spread into `appRouter`.
 *
 * Every layer exports a single fixed binding, `routers`, mapping top-level
 * `appRouter` key -> router. The map (rather than the old one-router-per-layer
 * `${manifest.name}Router` convention) exists because a layer can legitimately
 * own more than one top-level key — `layers/teams` owns `teams` *and* `invites`,
 * which is the API shape the client already calls. It also removes a real
 * failure mode: the old convention derived an export name by regex from the
 * manifest, so a mismatch only surfaced at Nuxt build time as an opaque "no
 * export named X"; a plain object under a fixed name is checked by `tsc`.
 *
 * Core layers and feature layers go through this same function. There is no
 * hand-written import list for core layers anywhere — `layers.core` in
 * config.ts feeds the very same `activeLayerNames` set (see
 * packages/app/nuxt.config.ts), so adding a name there is all it takes.
 */
function composeLayerRouters(root: string, layers: DiscoveredLayer[]) {
  const outFile = resolve(
    root,
    "packages/app/server/trpc/routers/.composition/layer-routers.ts",
  );
  const withRouter = layers.filter((layer) => layer.hasRouter);

  const imports = withRouter
    .map(
      (layer) =>
        `import { routers as ${importAlias(layer.dir)} } from "@nuxfire/layer-${layer.dir}/server/trpc/router";`,
    )
    .join("\n");

  const entries = withRouter
    .map((layer) => `  ...${importAlias(layer.dir)},`)
    .join("\n");

  write(
    outFile,
    `${GENERATED_HEADER}
${imports ? `\n${imports}\n` : ""}
export const layerRouters = {${entries ? `\n${entries}\n` : ""}};
`,
  );

  return { outFile, count: withRouter.length };
}

/**
 * `packages/app/app/composables/.composition/layer-navigation.ts` — the list
 * `useLayerNavigation()` reads sidebar entries from.
 *
 * Unlike the tRPC composition above, nothing here needs parsing: the manifest
 * is the package's own default export, so this file just re-exports it and
 * lets Nuxt's bundler resolve the import. No regex ever touches the nested
 * `navigation.sidebar` objects.
 */
function composeLayerNavigation(root: string, layers: DiscoveredLayer[]) {
  const outFile = resolve(
    root,
    "packages/app/app/composables/.composition/layer-navigation.ts",
  );

  const imports = layers
    .map(
      (layer) =>
        `import ${layer.name}Manifest from "@nuxfire/layer-${layer.dir}";`,
    )
    .join("\n");

  const entries = layers.map((layer) => `  ${layer.name}Manifest,`).join("\n");

  write(
    outFile,
    `${GENERATED_HEADER}
${imports ? `\n${imports}\n` : ""}
import type { LayerManifest } from "@nuxfire/layer-types";

export const layerManifests: LayerManifest[] = [${
      entries ? `\n${entries}\n` : ""
    }];
`,
  );

  return { outFile, count: layers.length };
}

/**
 * Discovers every Nuxt layer under `layers/` and (re)writes both composition
 * files to match. Idempotent and safe to call on every Nuxt config load — with
 * zero layers it writes a stable, empty `layerRouters = {}` and an empty
 * `layerManifests = []`.
 *
 * `activeLayerNames`, when given, filters discovery down to layers that are
 * BOTH present on disk AND turned on in `config.ts`'s `layers.core`/
 * `layers.features` — the same set `packages/app/nuxt.config.ts` computes for
 * its own `extends`. Without this filter, a layer switched off in config.ts
 * would still get its tRPC router mounted and its sidebar link rendered (the
 * link pointing at a page that `extends` had correctly dropped, a dead link,
 * not a removed feature) — `extends`, the tRPC composition and the nav
 * composition all have to agree on "active" from the same source, or
 * "desativado" stops being a real guarantee. Omit it only for the standalone
 * CLI debug entry point below, where "show me everything on disk" is the
 * useful default.
 */
export function composeLayers(
  root: string = resolve(here, ".."),
  activeLayerNames?: Iterable<string>,
) {
  const discovered = discoverLayers(resolve(root, "layers"));
  const active = activeLayerNames
    ? discovered.filter((l) => new Set(activeLayerNames).has(l.name))
    : discovered;

  const routers = composeLayerRouters(root, active);
  const navigation = composeLayerNavigation(root, active);

  const names = active.map((l) => l.name).join(", ") || "none";
  const skipped = discovered.length - active.length;
  console.log(
    `compose-layers: ${active.length} active layer(s) [${names}]` +
      (skipped ? ` (${skipped} on disk but not active in config.ts)` : "") +
      ` -> ${routers.count} router module(s) in ${routers.outFile}, ${navigation.count} manifest(s) in ${navigation.outFile}`,
  );

  return {
    layers: active,
    outFile: routers.outFile,
    navigationFile: navigation.outFile,
  };
}

// Allow `bun scripts/compose-layers.ts` as a standalone debug entry point.
// `require.main === module` doesn't exist under ESM and Bun's `import.meta.main`
// isn't portable to a plain Node/jiti import — comparing the invoked file path
// is the one check that works identically in both runtimes.
if (
  process.argv[1] &&
  fileURLToPath(import.meta.url) === resolve(process.argv[1])
) {
  composeLayers();
}
