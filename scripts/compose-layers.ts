import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "fs";
import { resolve } from "path";
import { fileURLToPath } from "node:url";

// Generates the tRPC composition file that `packages/app/server/trpc/routers/
// index.ts` spreads into `appRouter`. A layer is picked up when it has BOTH a
// `layer.manifest.ts` (which names it) and a `server/trpc/router.ts`.
//
// This is called automatically from `packages/app/nuxt.config.ts` on every
// `nuxt dev`/`build`/`generate`/`typecheck`/`prepare` invocation — there is no
// manual step to remember. Running `bun scripts/compose-layers.ts` by hand
// still works (useful to inspect the output without booting Nuxt), it just
// calls the same function.
//
// `fileURLToPath(import.meta.url)` rather than Bun's `import.meta.dir`: this
// module is imported both as a standalone Bun script and from inside Nuxt's
// config loader (c12/jiti), and must resolve the same way in both — matches
// the convention already used in `packages/web/nuxt.config.ts`.
const here = fileURLToPath(new URL(".", import.meta.url));

interface DiscoveredLayer {
  /** Directory name under `layers/`, also the npm package suffix. */
  dir: string;
  /** `name` field from the manifest — the key the router is mounted under. */
  name: string;
}

// The manifest is TypeScript importing `@nuxfire/layer-types`, so it can't be
// `import()`ed here without resolving the whole workspace just to read one
// string field. The `name` field is a string literal by contract — read it
// textually, and fall back to the directory name, which the naming
// convention requires to match anyway.
function readManifestName(dir: string, fallback: string): string {
  const text = readFileSync(resolve(dir, "layer.manifest.ts"), "utf8");
  return text.match(/\bname:\s*["'`]([^"'`]+)["'`]/)?.[1] ?? fallback;
}

function discoverLayers(layersDir: string): DiscoveredLayer[] {
  if (!existsSync(layersDir)) return [];

  const found: DiscoveredLayer[] = [];

  for (const entry of readdirSync(layersDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;

    const dir = resolve(layersDir, entry.name);
    if (!existsSync(resolve(dir, "layer.manifest.ts"))) continue;
    if (!existsSync(resolve(dir, "server/trpc/router.ts"))) continue;

    found.push({ dir: entry.name, name: readManifestName(dir, entry.name) });
  }

  return found.sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * Discovers every Nuxt feature layer under `layers/` and (re)writes
 * `packages/app/server/trpc/routers/.composition/feature-routers.ts` to match.
 * Idempotent and safe to call on every Nuxt config load — with zero layers it
 * writes a stable, empty `featureRouters = {}`.
 */
export function composeLayers(root: string = resolve(here, "..")) {
  const layersDir = resolve(root, "layers");
  const outDir = resolve(root, "packages/app/server/trpc/routers/.composition");
  const outFile = resolve(outDir, "feature-routers.ts");

  const layers = discoverLayers(layersDir);

  const imports = layers
    .map(
      (layer) =>
        `import { ${layer.name}Router } from "@nuxfire/layer-${layer.dir}/server/trpc/router";`,
    )
    .join("\n");

  const entries = layers
    .map((layer) => `  ${layer.name}: ${layer.name}Router,`)
    .join("\n");

  const contents = `// GENERATED by scripts/compose-layers.ts — do not edit by hand.
// Regenerated automatically on every Nuxt config load (see
// packages/app/nuxt.config.ts); \`bun scripts/compose-layers.ts\` also works
// standalone if you just want to inspect the output.
${imports ? `\n${imports}\n` : ""}
export const featureRouters = {${entries ? `\n${entries}\n` : ""}};
`;

  mkdirSync(outDir, { recursive: true });
  writeFileSync(outFile, contents);

  console.log(
    `compose-layers: ${layers.length} layer router(s) [${layers.map((l) => l.name).join(", ") || "none"}] -> ${outFile}`,
  );

  return { layers, outFile };
}

// Allow `bun scripts/compose-layers.ts` as a standalone debug entry point.
// `require.main === module` doesn't exist under ESM and Bun's `import.meta.main`
// isn't portable to a plain Node/jiti import — comparing the invoked file path
// is the one check that works identically in both runtimes.
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  composeLayers();
}
